// -- permissions ------------------------------------------------------------

export async function getPermissionsStatus(): Promise<Record<PermissionName, PermissionState>> {
  if (!isTauriAvailable()) {
    return { accessibility: 'unknown', screenRecording: 'unknown', microphone: 'unknown' };
  }
  return invoke<Record<PermissionName, PermissionState>>('get_permissions_status');
}

// -- events -----------------------------------------------------------------

/**
 * Subscribe to a Rust-emitted event. Returns an unsubscribe function.
 *
 * Metrics arrive here rather than over the WebSocket: sampling happens in Rust
 * at 1 Hz (DEC-003), and routing them through Python would add a hop, a
 * serialisation and a poll loop to the one thing that runs every second for the
 * entire session.
 */
export async function listen<T>(event: string, handler: (payload: T) => void): Promise<() => void> {
  const listener = tauri()?.event?.listen;
  if (listener === undefined) {
    return () => {};
  }
  return listener<T>(event, (e) => handler(e.payload));
}

export function onMetrics(handler: (metrics: SystemMetrics) => void): Promise<() => void> {
  return listen<SystemMetrics>('metrics:update', handler);
}

export function onSidecarState(handler: (state: SidecarState) => void): Promise<() => void> {
  return listen<SidecarState>('sidecar:state', handler);
}
